using Domovoy.Core.Domain;
using Domovoy.Core.Reference;
using Microsoft.EntityFrameworkCore;

namespace Domovoy.Core.Data;

/// <summary>
/// Уточняющие вопросы и зоны ответственности.
///
/// Ответственность за бытовой сбой — это почти всегда граница, а не «или-или»: внутри
/// квартиры отвечает собственник, в общем имуществе дома — управляющая организация,
/// до стены дома — ресурсоснабжающая, за дворовой территорией — город. Уточняющий вопрос
/// как раз и определяет, по какую сторону границы находится проблема.
///
/// Основания указаны в каждой строке: ЖК РФ определяет состав общего имущества,
/// ПП РФ № 354 — качество коммунальных услуг, ПП РФ № 491 — границы эксплуатационной
/// ответственности.
/// </summary>
public static class SeedClarifyingOptions
{
    private static readonly DateOnly Today = new(2026, 9, 20);

    public static async Task ApplyAsync(DomovoyDbContext db, CancellationToken ct = default)
    {
        if (await db.ClarifyingOptions.AnyAsync(ct)) return;

        var categories = await db.ProblemCategories.ToDictionaryAsync(c => c.Code, ct);
        var zones = await db.ResponsibilityZones.ToDictionaryAsync(z => z.Code, ct);

        void Option(string categoryCode, string zoneCode, string text,
            string explanation, string legalBasis, int sort, bool emergency = false)
        {
            db.ClarifyingOptions.Add(new ClarifyingOption
            {
                ProblemCategoryId = categories[categoryCode].Id,
                ResponsibilityZoneId = zones[zoneCode].Id,
                Text = text,
                Explanation = explanation,
                LegalBasis = legalBasis,
                IsEmergency = emergency,
                SortOrder = sort,
                Source = DataSource.Official,
                SourceName = legalBasis,
                ActualAt = Today,
                Territory = "РФ"
            });
        }

        // Протечка. Кровля и стояки — общее имущество; разводка внутри квартиры — зона
        // собственника; сосед сверху — вообще не про управляющую организацию.
        Option("leak_emergency", "ads", "Течёт прямо сейчас, заливает",
            "Это авария. Вызов аварийно-диспетчерской службы — первоочередное действие, "
            + "анкета здесь только теряет время.",
            "ПП РФ от 27.03.2018 № 331", 10, emergency: true);

        Option("leak_emergency", "uk", "С потолка или по стене, верхний этаж",
            "Кровля входит в состав общего имущества дома, за её содержание отвечает "
            + "управляющая организация.",
            "ЖК РФ, ст. 36; ПП РФ от 13.08.2006 № 491", 20);

        Option("leak_emergency", "uk", "Из стояка или общедомовой трубы",
            "Стояки и общедомовые инженерные системы — общее имущество дома.",
            "ПП РФ от 13.08.2006 № 491", 30);

        Option("leak_emergency", "resident", "От соседей сверху",
            "Разводка внутри квартиры — зона ответственности её собственника. "
            + "Управляющая организация фиксирует факт залива актом, но ущерб возмещает сосед.",
            "ЖК РФ, ст. 30", 40);

        // Отопление. Граница проходит по стене дома.
        Option("heating", "uk", "Холодно во всей квартире, у соседей тоже",
            "Проблема общедомовая: внутридомовая система отопления относится к общему "
            + "имуществу, и отвечает за неё управляющая организация.",
            "ПП РФ от 06.05.2011 № 354; ПП РФ № 491", 10);

        Option("heating", "rso", "Во всём доме или квартале нет отопления",
            "Сбой за границей дома — это зона ресурсоснабжающей организации. "
            + "Управляющая организация обязана передать обращение ей.",
            "ПП РФ от 06.05.2011 № 354", 20);

        Option("heating", "resident", "Холодно только в одной комнате",
            "Скорее всего дело во внутриквартирной разводке или в радиаторе — "
            + "это зона собственника помещения.",
            "ЖК РФ, ст. 30", 30);

        // Горячая вода.
        Option("hot_water", "uk", "Воды нет только у меня или в подъезде",
            "Внутридомовая система горячего водоснабжения — общее имущество дома.",
            "ПП РФ от 13.08.2006 № 491", 10);

        Option("hot_water", "rso", "Воды нет во всём доме или районе",
            "Подача ресурса до границы дома — обязанность ресурсоснабжающей организации.",
            "ПП РФ от 06.05.2011 № 354", 20);

        Option("hot_water", "uk", "Вода идёт, но недостаточно горячая",
            "Норматив температуры горячей воды нарушен. Зафиксировать несоответствие "
            + "и составить акт обязана управляющая организация.",
            "ПП РФ от 06.05.2011 № 354, приложение 1", 30);

        // Содержание общего имущества и двора: граница дома и придомовой территории.
        Option("common_area", "uk", "В подъезде: уборка, освещение, двери",
            "Подъезд, лестничные клетки и освещение в них — общее имущество дома.",
            "ЖК РФ, ст. 36", 10);

        Option("common_area", "uk", "Лифт не работает",
            "Лифт входит в состав общего имущества. Управляющая организация отвечает "
            + "за его исправность и договор с обслуживающей организацией.",
            "ЖК РФ, ст. 36; ПП РФ № 491", 20);

        Option("common_area", "uk", "Во дворе, на придомовой территории",
            "Если участок сформирован и входит в состав общего имущества — отвечает "
            + "управляющая организация.",
            "ЖК РФ, ст. 36", 30);

        Option("common_area", "municipality", "На улице за двором: дорога, тротуар, фонари",
            "За границей придомовой территории отвечает муниципальная служба, "
            + "а не управляющая организация.",
            "ЖК РФ, ст. 36", 40);

        // Мусор: площадка обычно муниципальная, вывоз — региональный оператор.
        Option("waste", "municipality", "Мусор не вывозят с площадки",
            "Вывоз твёрдых коммунальных отходов — обязанность регионального оператора; "
            + "обращение подаётся через управляющую организацию или напрямую оператору.",
            "ПП РФ от 12.11.2016 № 1156", 10);

        Option("waste", "uk", "Грязно на площадке или переполнены баки в доме",
            "Содержание мусоропровода и площадки в составе общего имущества — "
            + "зона управляющей организации.",
            "ПП РФ от 13.08.2006 № 491", 20);

        // Начисления.
        Option("billing", "uk", "Вопрос по строке за содержание жилья",
            "Начисления за содержание и текущий ремонт формирует управляющая организация, "
            + "она же обязана их обосновать.",
            "ПП РФ от 15.05.2013 № 416", 10);

        Option("billing", "rso", "Вопрос по коммунальной услуге: вода, тепло, электричество",
            "Если договор заключён напрямую с ресурсоснабжающей организацией, "
            + "начисления объясняет она.",
            "ПП РФ от 06.05.2011 № 354", 20);

        await db.SaveChangesAsync(ct);
    }
}
