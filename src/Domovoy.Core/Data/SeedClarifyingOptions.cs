///
/// Состав тем — по каталогу docs/product/08-problem-catalog.md. Там, где у темы другой
/// адресат, чем у категории, у неё и свой срок: жалоба на качество коммунальной услуги,
/// обращение по содержанию общего имущества и обращение в орган местного самоуправления
/// регулируются разными актами.
///
/// Подписи короткие: длинный текст в кнопке MAX обрезается. Подробность переносится
