    public const int MaxButtonLabel = 34;

    public static async Task ApplyAsync(DomovoyDbContext db, CancellationToken ct = default)
    {
        if (await db.ClarifyingOptions.AnyAsync(ct)) return;

        var categories = await db.ProblemCategories.ToDictionaryAsync(c => c.Code, ct);
        var zones = await db.ResponsibilityZones.ToDictionaryAsync(z => z.Code, ct);

        ClarifyingOption Option(string categoryCode, string zoneCode, string text,
            string explanation, string legalBasis, int sort, bool emergency = false)
        {
            if (text.Length > MaxButtonLabel)
            {
                throw new InvalidOperationException(
                    $"Подпись «{text}» длиннее {MaxButtonLabel} символов и обрежется в кнопке.");
            }

            var option = new ClarifyingOption
            {
                ProblemCategoryId = categories[categoryCode].Id,
                ResponsibilityZoneId = zones[zoneCode].Id,
                Text = text,
                Explanation = explanation,
                LegalBasis = legalBasis,
                IsEmergency = emergency,
                SortOrder = sort,
                Source = DataSource.Official,
                SourceName = legalBasis,
                ActualAt = CatalogDate,
                Territory = "РФ"
            };

            db.ClarifyingOptions.Add(option);
            return option;
        }

        // Срок темы, отличный от срока категории.
        void Deadline(ClarifyingOption option, int amount, DeadlineUnit unit,
            string legalBasis, string comment) =>
            db.NormativeDeadlines.Add(new NormativeDeadline
            {
                ProblemCategoryId = option.ProblemCategoryId,
                ClarifyingOption = option,
                Amount = amount,
                Unit = unit,
